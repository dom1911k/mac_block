import Foundation

/// Generates the pf anchor. Lives in IntentCore so it can be unit-tested and checked by `--self-test`.
///
/// Policy: everything outbound is blocked except
///   - loopback (our DNS resolver lives there),
///   - what any network needs to come up (DHCP, IPv6 neighbor discovery, NTP, Bonjour),
///   - DNS to the upstream filter servers (only from root-owned sockets, if enabled),
///   - IPs in <im_allow>, which only the resolver fills, for names the current mode allows.
/// Rules don't name an interface, so they apply to Wi-Fi, Ethernet, USB tethering and VPN tunnels alike.
public enum PFRules {
    public static func anchor(config: IntentConfig, restrictUpstreamToRoot: Bool) -> String {
        let table = Paths.pfTable
        var s = "# Generated by intentmoded \(BuildInfo.version). Do not edit: it is regenerated on every start.\n"
        s += "table <\(table)> persist\n"
        s += "table <im_upstream> const persist { \(config.upstreamDns.joined(separator: ", ")) }\n"
        if !config.dohBlockIps.isEmpty {
            s += "table <im_doh> const persist { \(config.dohBlockIps.joined(separator: ", ")) }\n"
        }
        s += """
        # Loopback: our resolver on 127.0.0.1:53 and local dev servers. Stateless so flushing states never breaks it.
        pass quick on lo0 all no state
        # Basics a network needs to come up.
        pass out quick inet proto udp from any port 68 to any port 67 keep state
        pass out quick inet6 proto udp from any port 546 to any port 547 keep state
        pass quick inet6 proto icmp6 all icmp6-type { routersol, routeradv, neighbrsol, neighbradv, redir } keep state
        pass out quick proto udp from any to any port 123 keep state
        pass out quick proto udp from any to { 224.0.0.251, ff02::fb } port 5353 keep state

        """
        if config.pfAllowInboundSsh {
            // Unmatched inbound packets pass without creating state, so the replies would hit our
            // final block rule. This rule creates state for incoming SSH so Remote Login works.
            s += "# Incoming SSH (Remote Login) as an emergency way in.\n"
            s += "pass in quick proto tcp from any to any port 22 flags S/SA keep state\n"
        }
        s += "# DNS goes only to the filtering upstream servers.\n"
        s += "pass out quick proto { tcp, udp } from any to <im_upstream> port 53 \(restrictUpstreamToRoot ? "user root " : "")keep state\n"
        s += "# DNS-over-TLS and known DNS-over-HTTPS servers are always blocked.\n"
        s += "block return out quick proto { tcp, udp } from any to any port 853\n"
        s += "block return out quick from any to <im_upstream>\n"
        if !config.dohBlockIps.isEmpty { s += "block return out quick from any to <im_doh>\n" }
        s += "# Addresses the resolver handed out for allowed names.\n"
        s += "pass out quick from any to <\(table)> keep state\n"
        s += "# Everything else: refused immediately (return), so apps fail fast instead of hanging.\n"
        s += "block return out quick all\n"
        return s
    }

    /// Apple's default main ruleset (/etc/pf.conf). Loaded only if the main ruleset has lost
    /// its `anchor "com.apple/*"` hook and /etc/pf.conf can't restore it.
    public static let appleDefaultMain = """
    scrub-anchor "com.apple/*"
    nat-anchor "com.apple/*"
    rdr-anchor "com.apple/*"
    dummynet-anchor "com.apple/*"
    anchor "com.apple/*"
    load anchor "com.apple" from "/etc/pf.anchors/com.apple"

    """
}
